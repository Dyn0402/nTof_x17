#!/usr/bin/env python3
"""collect_numbers.py -- gather every number the review quotes into NUMBERS.md, from the result files of papers/paper2/hits_daq.

Sources: results/universal.json (ratio vs angle, end/interior fits, pitch scan, literature points), depth_ratio summary
(same-time share and its growth), remedies run1/run2 (hit-level corrections vs the waveform fit), ghost_census,
phase_closure summary, toy scans, the coupling report tables (quoted by hand where they are only in the html).
"""
import json
import os
import sys

import numpy as np

HD = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', 'paper2', 'hits_daq'))
WD = os.environ.get('WORK_DATA', '/media/ucla/work') + '/paper2_hits'
OUT = os.path.join(os.path.dirname(__file__), '..', 'NUMBERS.md')
L_GAP, PITCH = 28.08, 0.78


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    lines = ['# Numbers quoted in the review (generated by scripts/collect_numbers.py)\n']
    U = load(os.path.join(HD, 'results', 'universal.json'))
    if U:
        lines.append('## Ratio tan_reco/tan_true against |tan| (det3, V0 leading-edge hits, amplitude-weighted line)\n')
        lines.append('| curve | ' + ' | '.join(f'{r["tan"]:.2f}' for r in U['curves']['data|run1|x|u_dream']) + ' | a (end) | b (interior) | C = a (L/p)^2 |')
        lines.append('|---|' + '---|' * (len(U['curves']['data|run1|x|u_dream']) + 3))
        for key in ['data|run1|x|u_dream', 'data|run2|x|u_dream', 'data|run1|y|u_dream', 'data|run2|y|u_dream', 'data|run1|x|ue_dream', 'data|run1|x|u_ideal', 'data|run1|x|W',
                    'resim|x|base|u_dream', 'resim|x|metal|u_dream', 'resim|x|dp0|u_dream', 'resim|x|point|u_dream', 'resim|x|s0_45|u_dream',
                    'resim|y|base|u_dream', 'resim|y|rc0|u_dream', 'resim|y|metal|u_dream', 'resim|y|point|u_dream', 'resim|y|rc2|u_dream', 'resim|y|rc5|u_dream']:
            rows = U['curves'].get(key, [])
            f = U['fits'].get(key)
            cells = [f'{r["ratio"]:.3f}' for r in rows]
            cells += [''] * (len(U['curves']['data|run1|x|u_dream']) - len(cells))
            fs = [f'{f["a"]:.4f}', f'{f["b"]:+.4f}', f'{f["a"] * (L_GAP / PITCH) ** 2:.1f}'] if f else ['', '', '']
            lines.append(f'| {key} | ' + ' | '.join(cells) + ' | ' + ' | '.join(fs) + ' |')
        lines.append('\nPitch scan (strips summed k at a time), C = a (L/(k p))^2 ... reported as a and b per k:\n')
        for arm in ('data', 'point', 'metal', 'base'):
            lines.append(f'- {arm}: ' + ', '.join(f'k{k}: a={U["fits"][f"gang|x|{arm}|k{k}"]["a"]:.4f} b={U["fits"][f"gang|x|{arm}|k{k}"]["b"]:+.3f}' for k in (1, 2, 3, 4, 6) if f'gang|x|{arm}|k{k}' in U['fits']))
        lines.append('\nLiterature points (tan ratio, N = L tan / p, Lambda = sigma_T(L) / (L tan)):\n')
        for l in U['lit']:
            lines.append(f'- {l["label"]}: tan {l["tan_true"]:.3f}, ratio {l["ratio"]:.3f}, N {l["N"]:.1f}, (ratio-1) N^2 = {(l["ratio"] - 1) * l["N"] ** 2:.2f}, Lambda {l["Lambda"]:.3f}  [{l["note"]}]')
    D = load(os.path.join(WD, 'depth', 'full', 'summary.json'))
    if D:
        g = np.array(D['grid'])
        lines.append('\n## Depth-resolved lateral sharing on near-normal tracks (chamber A, Runs 1+2)\n')
        for view in 'xy':
            for wcls in ('tight', 'all'):
                key = f'{view}|{wcls}|phall'
                C = D['curves'].get(key)
                if not C:
                    continue
                lines.append(f'\n### {view}, {"|tan| < 0.008" if wcls == "tight" else "|tan| < 0.034"}, n = {C["n"]} planes\n')
                lines.append('| arm | r1(0) | r1(400) | r1(800) | r2(0) | r2(400) | r2(800) | sigma_eff(0) | sigma_eff(400) | sigma_eff(800) | d(sigma^2)/dt 100-700 ns [1e-4 mm^2/ns] | sigma^2 intercept |')
                lines.append('|---|---|---|---|---|---|---|---|---|---|---|---|')
                m = (g >= 100) & (g <= 700)
                for name in ('data', 'pass', 'metal', 'nodiff', 'norc', 'Dp18', 'Dp20', 's025', 's035', 'pureK', 'free'):
                    if name not in C:
                        continue
                    o = C[name]
                    i0, i4, i8 = [int(np.argmin(np.abs(g - t))) for t in (0, 400, 800)]
                    sg = np.array(o['sigma'])
                    ok = m & np.isfinite(sg)
                    pf = np.polyfit(g[ok], sg[ok] ** 2, 1) if ok.sum() > 3 else (np.nan, np.nan)
                    lines.append(f'| {name} | {o["r1"][i0]:.3f} | {o["r1"][i4]:.3f} | {o["r1"][i8]:.3f} | {o["r2"][i0]:.3f} | {o["r2"][i4]:.3f} | {o["r2"][i8]:.3f} | {sg[i0]:.3f} | {sg[i4]:.3f} | {sg[i8]:.3f} | {pf[0] * 1e4:.2f} | {pf[1]:.3f} |')
                if 'r1_err' in C['data']:
                    e = C['data']
                    lines.append(f'\ndata bootstrap errors: r1 {e["r1_err"][i0]:.3f}/{e["r1_err"][i4]:.3f}/{e["r1_err"][i8]:.3f}, r2 {e["r2_err"][i0]:.3f}/{e["r2_err"][i4]:.3f}/{e["r2_err"][i8]:.3f}')
        lines.append('\n### near/far neighbour over centre at t - t0 = 0 by |phase| bin (|tan| < 0.034)\n')
        lines.append('| view | phase bin | n | data near/far | pass | free (sigma0 0.25 + k1 0.06) | pureK (sigma0 0.033 + k1 0.13) | metal |')
        lines.append('|---|---|---|---|---|---|---|---|')
        for view in 'xy':
            for ib in range(3):
                C = D['curves'].get(f'{view}|all|ph{ib}')
                if not C:
                    continue
                i0 = int(np.argmin(np.abs(g - 0)))
                cells = [f'{C[n]["rnear"][i0]:.3f}/{C[n]["rfar"][i0]:.3f}' for n in ('data', 'pass', 'free', 'pureK', 'metal')]
                lines.append(f'| {view} | {D["phase_bins"][ib]:.2f}-{D["phase_bins"][ib + 1]:.2f} | {C["n"]} | ' + ' | '.join(cells) + ' |')
    for run in ('run1', 'run2'):
        R = load(os.path.join(WD, 'remedies', f'{run}.json'))
        if not R:
            continue
        lines.append(f'\n## Hit-level remedies, det3 {run} ({R["meta"]["n_planes"]} planes), angle s68 [deg] and median steepness [deg] against M3\n')
        lines.append('| tier | view | implied v [um/ns] | naive s68 | steep | steep 0.05-0.1 | 0.1-0.2 | 0.2-0.3 | 0.3-0.5 | H0 s68 | H0 in5 |')
        lines.append('|---|---|---|---|---|---|---|---|---|---|---|')
        for view in 'xy':
            V = R['views'][view]
            W = V['W']
            lines.append(f'| **W (waveform fit)** | {view} | | {W["all"]["s68"]:.2f} | {W["all"]["steep"]:+.2f} | ' + ' | '.join(f'{W[b]["steep"]:+.2f}' for b in ('0.05-0.1', '0.1-0.2', '0.2-0.3', '0.3-0.5')) + f' | | {W["all"]["frac_in5"]:.3f} |')
            for k in ('dream', 'dream_rob', 'dream_e50', 'dream_e25', 'dream_e17', 'dream_shift', 'dream_sub07', 'dream_sub15', 'dream_sub15_rob', 'dream_sub15_shift', 'dream_sub20', 'dream_sub30',
                      'cw', 'cw_rob', 'cw_shift', 'cw_sub15_rob', 'cw_sub15_shift', 'cw_sub30', 'ideal', 'ideal_rob', 'ideal_shift', 'ideal_sub15_shift', 'totmid', 'totmid_rob'):
                t = V['tiers'].get(k)
                if not t:
                    continue
                nv, h0 = t['naive'], t['H0']
                f = lambda x: f'{x:+.2f}' if x is not None else 'n/a'  # noqa: E731
                gg = lambda x: f'{x:.2f}' if x is not None else 'n/a'  # noqa: E731
                lines.append(f'| {k} | {view} | {t["implied_v"] or 0:.1f} | {gg(nv["all"]["s68"])} | {f(nv["all"]["steep"])} | ' + ' | '.join(f(nv[b]['steep']) for b in ('0.05-0.1', '0.1-0.2', '0.2-0.3', '0.3-0.5')) + f' | {gg(h0["all"]["s68"])} | {h0["all"]["frac_in5"]:.3f} |')
    Gc = load(os.path.join(HD, 'results', 'ghost_census_sat_det3.json'))
    if Gc:
        lines.append('\n## Ghost strips (hits beyond the column ends by > 0.5 pitch), det3 Run 1, per plane\n')
        lines.append('| view | tan bin | arm | planes | hits/plane | ghosts/plane | mesh end | cathode end | > 1.5 pitch |')
        lines.append('|---|---|---|---|---|---|---|---|---|')
        for k, o in Gc.items():
            lines.append(f'| {o["view"]} | {o["tan_lo"]}-{o["tan_hi"]} | {o["arm"]} | {o["n_planes"]} | {o["hits_per_plane"]:.2f} | {o["ghosts_per_plane"]:.2f} | {o["ghost_mesh"]:.2f} | {o["ghost_cathode"]:.2f} | {o["far_per_plane"]:.2f} |')
    P = load(os.path.join(WD, 'phasecl', 'full', 'summary.json'))
    if P:
        lines.append('\n## Phase-test closure: near/far early-charge ratio by |phase| bin, data and known-truth windows (pass refit of p0)\n')
        lines.append('| group | n | ' + ' | '.join(f'{P["phase_bins"][i]:.1f}-{P["phase_bins"][i + 1]:.1f}' for i in range(len(P['phase_bins']) - 1)) + ' | p0 refit MAD [mm] |')
        lines.append('|---|---|' + '---|' * len(P['phase_bins']))
        for k, rec in P['groups'].items():
            cells = [f'{b["near"]:.3f}/{b["far"]:.3f}' if b else '-' for b in rec['bins']]
            lines.append(f'| {k} | {rec["n"]} | ' + ' | '.join(cells) + f' | {rec.get("dp0_mad_mm", float("nan")):.3f} |')
    Ch = load(os.path.join(HD, 'results', 'chambers_C.json'))
    if Ch:
        lines.append('\n## The strip-end coefficient on four chambers (bootstrap windows of the golden rows; truth = the fit w; L = 28.08 mm for all)\n')
        lines.append('| chamber | row | planes X/Y | Dp | D_RC [mm^2/ns] | view | data C | model | metallic | RC off | no diffusion | geometry | data b | toy law C_X |')
        lines.append('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
        for det, ch in Ch['chambers'].items():
            for view in 'xy':
                A = ch['views'].get(view, {}).get('arms', {})
                g = lambda k: (f"{A[k]['C']:.2f}" + (f" +- {A[k]['C_err']:.2f}" if 'C_err' in A[k] else '') + (' (coarse)' if A[k].get('coarse') else '')) if k in A else '-'
                lines.append(f"| {ch['name']} ({det}) | {ch['row']} | {ch['views']['x']['n']}/{ch['views']['y']['n']} | {ch['hyper']['Dp']} | {ch['hyper']['rc_D_y']:.2e} | {view} | {g('data')} | {g('model')} | {g('metallic')} | {g('rc0')} | {g('Dp0')} | {g('point')} | {A['data']['b']:+.3f} | {ch['toy_law_C_X']:.2f} |" if 'data' in A else f"| {ch['name']} ({det}) | {ch['row']} | | | | {view} | too few planes | | | | | | | |")
    for scan in ('arms', 'pitch', 'estimators', 'detectors'):
        T = load(os.path.join(HD, 'results', f'toy_{scan}.json'))
        if not T:
            continue
        lines.append(f'\n## Toy scan: {scan} (ntr = {T["ntr"]} tracks per point)\n')
        for name, cfg in T['configs'].items():
            pr = cfg['params']
            lines.append(f'\n**{name}**: ' + ', '.join(f'{k}={v:.4g}' for k, v in pr.items()))
            lines.append('| estimator/correction | C | b |')
            lines.append('|---|---|---|')
            for k, f in cfg['fits'].items():
                if f:
                    lines.append(f'| {k} | {f["C"]:.2f} | {f["b"]:+.4f} |')
            tans = sorted(cfg['curves'].keys(), key=float)
            keys = [k for k in ('dream_plain', 'dream_rob', 'dream_shift', 'cw_plain', 'cw_rob', 'cw_shift', 'ideal_plain', 'fd_plain', 'fd_rob', 'peak_plain', 'peak_rob') if any(k in cfg['curves'][t] for t in tans)]
            lines.append('\n| tan | ' + ' | '.join(keys) + ' |')
            lines.append('|---|' + '---|' * len(keys))
            for t in tans:
                lines.append(f'| {float(t):.3f} | ' + ' | '.join(f'{cfg["curves"][t][k]["ratio"]:.3f}' if k in cfg['curves'][t] else '' for k in keys) + ' |')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('wrote', OUT, len(lines), 'lines')


if __name__ == '__main__':
    main()
