#!/usr/bin/env python3
"""make_tiers_table.py -- Paper IIa Table (sec. 6): hits (H0 / hits line), H2c and W on the same planes.

Reads the scored tables in results/ and writes ../tables/tiers.tex (a LaTeX tabular, \\input by sections/06).

  det3 (chamber A), cosmic bench, both Paper I runs, against M3:
      results/ana1106_tiers_{sat,p2}_det3.json   H0 = V0_dream line with (a, k) fitted to M3 on the other half (tiers.py)
      results/ana1106_h2c_{sat,p2}_det3.json     H2c = the forward model fitted to the hit lists (h2c.py)
  SPS chamber E (det4) at the 25.4 deg stage, CO2, inclined view (Y), against the stage angle:
      results/sps_h2crow_score.json              hits line tan = u / v and H2c, both with the row's own v (DAG 4646000)

Scores (tiers.py / sps_score.py): s68 = 68th percentile of |d - median d| over |d| <= 5 deg, in5 = fraction with
|d| <= 5 deg, steep = median of d sign(tan_ref) over |d| <= 5 deg [deg] (> 0 = reads too steep; signed median d
would flip with the beam's negative angle), d = reconstructed minus reference angle.

    ../../../.venv/bin/python make_tiers_table.py
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')
OUT = os.path.join(HERE, '..', 'tables', 'tiers.tex')

RUNS = (('sat', 'Run 1'), ('p2', 'Run 2'))
SPS_ROWS = ('run57_rot25_co2__d550', 'run57_rot25_co2__d600', 'run57_rot25_co2__d650', 'run57_rot25_co2__d700',
            'run59_co2__co2')
REGISTRY = os.path.join(HERE, '..', '..', '..', 'rerun', 'sps_registry.csv')


def load(name):
    with open(os.path.join(RES, name)) as f:
        return json.load(f)


def cells(s):
    """s68 / in5 / steep of a score dict"""
    return f'{s["s68"]:.2f} & {100 * s["frac_in5"]:.0f} & ${s["steep"]:+.2f}$'


def det3_rows():
    out = []
    for key, label in RUNS:
        tiers = load(f'ana1106_tiers_{key}_det3.json')['views']
        h2c = load(f'ana1106_h2c_{key}_det3.json')
        for view in ('x', 'y'):
            t = tiers[view]
            c = h2c[f'{key}_det3/{view}']
            assert c['W']['n'] == t['W']['score']['all']['n'], (key, view, 'H2c and tiers not on the same planes')
            out.append(f'{label}, {view.upper()} & {t["n"]} & {cells(t["tiers"]["V0_dream"]["H0"]["all"])} & '
                       f'{cells(c["H2c"])} & {cells(t["W"]["score"]["all"])} \\\\')
    return out


def sps_rows():
    d = load('sps_h2crow_score.json')
    reg = {r['key']: r for r in csv.DictReader(open(REGISTRY))}
    out = []
    for key in SPS_ROWS:
        r = d['rows'][key]
        assert r['inclined']
        y = r['views']['y']
        label = f'{reg[key]["run"].replace("_", "~")}, {float(reg[key]["field_Vcm"]):.0f}\\,V/cm'
        out.append(f'{label} & {y["n"]} & {cells(y["tiers"]["V0_dream"]["score"]["all"])} & '
                   f'{cells(y["tiers"]["V0/H2c_dream"]["score"]["all"])} & {cells(y["W"]["all"])} \\\\')
    return out


def main():
    hdr = ('% generated by hits_daq/make_tiers_table.py -- do not edit by hand\n'
           '\\begin{tabular}{@{}lr rrr rrr rrr@{}}\n\\toprule\n'
           ' & & \\multicolumn{3}{c}{hits} & \\multicolumn{3}{c}{H2c} & \\multicolumn{3}{c}{W} \\\\\n'
           '\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}\\cmidrule(l){9-11}\n'
           ' & planes & $s_{68}$ & in5 & steep & $s_{68}$ & in5 & steep & $s_{68}$ & in5 & steep \\\\\n'
           ' & & [\\textdegree] & [\\%] & [\\textdegree] & [\\textdegree] & [\\%] & [\\textdegree] '
           '& [\\textdegree] & [\\%] & [\\textdegree] \\\\\n\\midrule\n')
    body = ['\\multicolumn{11}{@{}l}{\\emph{Chamber A, cosmic bench, against the M3 reference}} \\\\']
    body += det3_rows()
    body += ['\\midrule',
             '\\multicolumn{11}{@{}l}{\\emph{Chamber E, SPS, CO$_2$, inclined view at the 25.4\\textdegree{} stage, '
             'against the stage angle}} \\\\']
    body += sps_rows()
    tex = hdr + '\n'.join(body) + '\n\\bottomrule\n\\end{tabular}\n'
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write(tex)
    print(tex)
    print('wrote', os.path.relpath(OUT))


if __name__ == '__main__':
    main()
