#!/usr/bin/env python3
"""width_probe.py --det det3 [--tan-min 0.08] [--n 400] [--jobs 8] [--cache c.pkl --bundle b --out dir] [--toy SPEC]

Width–tilt trade, measured per event.  For each held-out plane with |tan_ref| >= tan_min, on a grid of lateral-width
laws (prompt footprint sigma_p0 x diffusion Dp), two fits with the profile switched OFF (one width per fit):
  free : the production fitter (wft.reco.fit_plane, pivot start)        -> w_free, chi2_free
  ref  : the slope pinned at the M3 angle (w_ref = tan_ref·kw·v + w0), p0 scanned ±1.5 mm, t0 + charge profile fitted
                                                                       -> chi2_ref
Questions it answers: (1) how much does the fitted slope move with the assumed width (the trade, per angle bin);
(2) which width law the data prefer at the free angle and at the M3 angle; (3) whether any width law makes the
M3 angle the chi2 minimum (chi2_ref - chi2_free -> 0) — if none does, the width law is not the whole mismatch.
--toy 'gen_s0=0.3,gen_dp=0.02' runs the same grid on toy waveforms generated by toy_closure.py's generator
(truth known) instead of the data.
Writes <out>/width_probe_<det>[_<tag>].npz: rows (eid, view, tan_ref, w_ref, s0, dpf, w_free, chi2_free, chi2_ref, dof, qsum,
chi2_fscan [the same p0 grid at w_free], p0_free, ref_mesh, t0_free).
"""
import argparse, json, os, pickle, sys
from concurrent.futures import ProcessPoolExecutor
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.environ.get('WFT_REPO') or os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, REPO); sys.path.insert(0, HERE)
S0 = [0.12, 0.24, 0.34, 0.44, 0.54]
DPF = [0.5, 0.75, 1.0, 1.25]
_EV = None; _CAL = None; _TOY = None


def _init(cache, bundle, k, toy):
    global _EV, _CAL, _TOY
    from wft.calib import CalibrationBundle
    from wft import model as wm, reco as wr
    _EV = pickle.load(open(cache, 'rb'))
    cal = CalibrationBundle.load(bundle)
    cal.hyper['sigma_p0_prof_x'] = []; cal.hyper['sigma_p0_prof_y'] = []
    wm.use_calibration(cal); wm.set_depth_bins(k); wm.COL_GUARD = 0.01; wr.PIVOT_START = True
    _CAL = cal; _TOY = toy


def toy_window(ev, plane, inj, rng):
    """Replace the real waveform by a toy one (same window, noise, gain, M3 angle) — see toy_closure.py."""
    import toy_closure as tc
    tc._CAL = _CAL
    from wft import model as wm
    P = ev[plane]; Wr = np.asarray(P['W'], float)
    tr = float(ev[f'tan_{plane}']); ref = float(ev[f'ref_mesh_{plane}'])
    v_gen = float(inj.get('gen_v', _CAL.v_drift))
    hg = tc.gen_hyper(_CAL, plane, inj)
    pos = np.asarray(P['pos'], float); ch = np.asarray(P['ch'], int); g = wm.GAIN[plane][ch]
    q = tc.charge_profile(v_gen, rng, inj, tr)
    mod = (wm.build_matrix(plane, pos, ref, tr * v_gen * 1e-3, tc.T0_TRUE, hg) @ q).reshape(len(pos), wm.NSAMP)
    mod *= (np.maximum(Wr, 0) / g[:, None]).sum() / max(mod.sum(), 1e-9)
    noise = np.maximum(np.asarray(P['noise'], float), 3.0)
    Wt = np.minimum(mod * g[:, None] + noise[:, None] * rng.standard_normal(mod.shape), wm.SAT)
    return dict(W=Wt, pos=pos, noise=P['noise'], ch=ch)


def one(job):
    eid, tan_min = job
    from wft import model as wm, reco as wr
    cal = _CAL; ev = _EV[eid]; rows = []
    rng = np.random.default_rng(7919 * int(eid) + 3)
    for vi, plane in enumerate('xy'):
        if plane not in ev:
            continue
        tr = float(ev[f'tan_{plane}'])
        if abs(tr) < tan_min:
            continue
        P = ev[plane] if _TOY is None else toy_window(ev, plane, _TOY, rng)
        W = np.asarray(P['W'])
        if W.shape[1] != wm.NSAMP:
            wm.set_nsamp(W.shape[1])
        ref = float(ev[f'ref_mesh_{plane}'])
        if _TOY is None:
            w_ref = (tr * cal.kw.get(plane, 1.0) * cal.v_drift + cal.w0.get(plane, 0.0)) * 1e-3
        else:
            w_ref = tr * float(_TOY.get('gen_v', cal.v_drift)) * 1e-3
        qsum = float(np.maximum(W, 0).sum())
        for s0 in S0:
            for dpf in DPF:
                h = dict(cal.hyper); h[f'sigma_p0_{plane}'] = s0; h['Dp'] = cal.hyper['Dp'] * dpf
                try:
                    f = wr.fit_plane(P, plane, cal, hyper=h)
                except Exception:
                    f = None
                if f is None:
                    continue
                best = np.inf
                for dp in np.arange(-1.5, 1.51, 0.3):
                    r = wm.fit_plane_raw(P, plane, ref + dp, w_ref, f.t0, hyper=h, fix_p0w=(ref + dp, w_ref))
                    best = min(best, r['chi2'])
                # the same p0 grid at the FITTED slope, so the grid granularity cancels in chi2_ref - chi2_fscan
                bestf = np.inf
                for dp in np.arange(-1.5, 1.51, 0.3):
                    r = wm.fit_plane_raw(P, plane, f.p0 + dp, f.w, f.t0, hyper=h, fix_p0w=(f.p0 + dp, f.w))
                    bestf = min(bestf, r['chi2'])
                rows.append((eid, vi, tr, w_ref * 1e3, s0, dpf, f.w * 1e3, f.chi2, best, f.dof, qsum, bestf, f.p0, ref, f.t0))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--det', required=True); ap.add_argument('--tan-min', type=float, default=0.08)
    ap.add_argument('--n', type=int, default=400); ap.add_argument('--start', type=int, default=180)
    ap.add_argument('--jobs', type=int, default=8); ap.add_argument('--k', type=int, default=24)
    ap.add_argument('--cache'); ap.add_argument('--bundle'); ap.add_argument('--toy', default=None)
    ap.add_argument('--tag', default=''); ap.add_argument('--steep-first', action='store_true')
    ap.add_argument('--out', default=os.path.expanduser('~/x17/cosmic_bench/model_audit/ws_widthtilt'))
    a = ap.parse_args()
    cache = a.cache or os.path.expanduser(f'~/x17/cosmic_bench/vladder/{a.det}/cache.pkl')
    bundle = a.bundle or os.path.expanduser(f'~/x17/cosmic_bench/model_audit/{a.det}/calib_bundle')
    toy = None if not a.toy else ({} if a.toy == 'base' else dict(kv.split('=', 1) for kv in a.toy.split(',')))
    C = pickle.load(open(cache, 'rb')); ids = sorted(C)[a.start:]
    ids = [i for i in ids if max(abs(C[i].get('tan_x', 0)), abs(C[i].get('tan_y', 0))) >= a.tan_min]
    if a.steep_first:
        ids.sort(key=lambda i: -max(abs(C[i].get('tan_x', 0)), abs(C[i].get('tan_y', 0))))
    ids = ids[:a.n]; del C
    print(f'{a.det}: {len(ids)} events, grid {len(S0)}x{len(DPF)}, toy={toy}', flush=True)
    with ProcessPoolExecutor(a.jobs, initializer=_init, initargs=(cache, bundle, a.k, toy)) as ex:
        rows = [r for rr in ex.map(one, [(i, a.tan_min) for i in ids], chunksize=1) for r in rr]
    os.makedirs(a.out, exist_ok=True)
    o = os.path.join(a.out, f'width_probe_{a.det}{"_" + a.tag if a.tag else ""}.npz')
    np.savez(o, per=np.array(rows, float), s0=S0, dpf=DPF, toy=json.dumps(toy), bundle=bundle)
    print('wrote', o, len(rows))


if __name__ == '__main__':
    main()
