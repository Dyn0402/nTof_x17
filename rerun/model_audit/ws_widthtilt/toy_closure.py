#!/usr/bin/env python3
"""toy_closure.py --det det3 [--n 400] [--jobs 4] [--inject KEY=VAL ...] [--tag T]

Closure test of the production plane fit (wft.reco.fit_plane: pivot start, sigma_p0 profile, column guard) on
waveforms GENERATED by the forward model itself.  Each toy re-uses one real held-out event's window (strip
positions, channels, per-strip noise, gain) and its M3 angle and mesh position; the truth is
    w_true = tan_ref * v,  p0 = ref_mesh,  t0 = 300 ns,
and the charge column is a straight track through the full 30 mm gap (uniform charge per depth, optionally with
Landau-like cluster fluctuations), scaled to the real event's total ADC sum.  White Gaussian noise at the strip's
noise, clipping at SAT.  If the fit returns w_fit/w_true = 1 at every angle, the compression seen on data (F4) is
model-vs-reality mismatch, not a property of the fitter.

--inject turns on a piece of physics in the GENERATOR only (the fit keeps the bundle model), e.g.
    gen_sigma_scale=0.8      generator footprint (sigma_p0 and Dp) x 0.8
    gen_dp=0.015             generator diffusion constant
    landau=1                 per-depth-bin charge ~ Landau-like (moyal) fluctuations
    gen_s0=0.42              generator prompt footprint (both views)
    gen_v=33                 generator drift velocity (the fit keeps the bundle v)
Writes <out>/toy_<det>_<tag>.npz with rows (eid, view, tan_ref, w_true, w_fit, chi2, dof, sigma_used, qsum).
"""
import argparse, json, os, pickle, sys
from concurrent.futures import ProcessPoolExecutor
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.environ.get('WFT_REPO') or os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, REPO)
_EV = None; _CAL = None; _INJ = None
GAP_MM = 30.0
T0_TRUE = 300.0


def _init(cache, bundle, k, inj):
    global _EV, _CAL, _INJ
    from wft.calib import CalibrationBundle
    from wft import model as wm, reco as wr
    _EV = pickle.load(open(cache, 'rb'))
    cal = CalibrationBundle.load(bundle)
    wm.use_calibration(cal); wm.set_depth_bins(k); wm.COL_GUARD = 0.01; wr.PIVOT_START = True
    _CAL = cal; _INJ = inj


def gen_hyper(cal, plane, inj):
    h = dict(cal.hyper)
    if 'gen_s0' in inj:
        h[f'sigma_p0_{plane}'] = float(inj['gen_s0'])
    if 'gen_sigma_scale' in inj:
        f = float(inj['gen_sigma_scale'])
        h[f'sigma_p0_{plane}'] = h.get(f'sigma_p0_{plane}', h['sigma_p0']) * f
        h['Dp'] = h['Dp'] * f
    if 'gen_dp' in inj:
        h['Dp'] = float(inj['gen_dp'])
    if 'gen_rcd' in inj:
        h['rc_D_y'] = h['rc_D_y'] * float(inj['gen_rcd'])
    if 'gen_asym' in inj and plane == 'x':
        h[f'rc_asym_{plane}'] = float(inj['gen_asym'])
    return h


def charge_profile(v, rng, inj, tan):
    """Charge per 60 ns depth bin for a straight track crossing the whole gap (uniform per unit depth)."""
    from wft import model as wm
    T = GAP_MM / (v * 1e-3)                                      # column duration [ns]
    ua = np.arange(wm.K) * wm.DT
    frac = np.clip((T - ua) / wm.DT, 0.0, 1.0)                    # partial last bin
    q = frac.copy()
    if int(inj.get('landau', 0)):
        # cluster-count + Landau-tail fluctuations per bin: moyal variates (location 1, scale 0.25)
        from scipy.stats import moyal
        q = q * np.clip(moyal.rvs(loc=1.0, scale=0.25, size=len(q), random_state=rng), 0.05, 20.0)
    return q


def one(eid):
    from wft import model as wm, reco as wr
    cal = _CAL; inj = _INJ; ev = _EV[eid]; rows = []
    rng = np.random.default_rng(1000003 * int(eid) + 17)
    for vi, plane in enumerate('xy'):
        if plane not in ev:
            continue
        P = ev[plane]
        Wr = np.asarray(P['W'], float)
        if Wr.shape[1] != wm.NSAMP:
            wm.set_nsamp(Wr.shape[1])
        tr = float(ev[f'tan_{plane}']); ref = float(ev[f'ref_mesh_{plane}'])
        v_gen = float(inj.get('gen_v', cal.v_drift))
        w_true = tr * v_gen * 1e-3                                # mm/ns
        hg = gen_hyper(cal, plane, inj)
        pos = np.asarray(P['pos'], float); ch = np.asarray(P['ch'], int)
        g = wm.GAIN[plane][ch]
        q = charge_profile(v_gen, rng, inj, tr)
        M = wm.build_matrix(plane, pos, ref, w_true, T0_TRUE, hg)
        mod = (M @ q).reshape(len(pos), wm.NSAMP)
        # scale to the real event's total (positive) ADC sum in gain-corrected units
        real = (np.maximum(Wr, 0) / g[:, None]).sum()
        s = real / max(mod.sum(), 1e-9)
        mod *= s
        noise = np.maximum(np.asarray(P['noise'], float), 3.0)
        Wt = mod * g[:, None] + noise[:, None] * rng.standard_normal(mod.shape)
        Wt = np.minimum(Wt, wm.SAT)
        Pt = dict(W=Wt, pos=pos, noise=P['noise'], ch=ch)
        try:
            f = wr.fit_plane(Pt, plane, cal)
        except Exception:
            f = None
        if f is None:
            continue
        rows.append((eid, vi, tr, w_true * 1e3, f.w * 1e3, f.chi2, f.dof,
                     float(getattr(f, '_sigma_p0', np.nan)), float(s * q.sum()), int((Wt >= wm.SAT).sum())))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--det', required=True); ap.add_argument('--n', type=int, default=400)
    ap.add_argument('--start', type=int, default=180); ap.add_argument('--jobs', type=int, default=4)
    ap.add_argument('--tan-min', type=float, default=0.0)
    ap.add_argument('--inject', nargs='*', default=[]); ap.add_argument('--tag', default='base')
    ap.add_argument('--cache'); ap.add_argument('--bundle')
    ap.add_argument('--out', default=os.path.expanduser('~/x17/cosmic_bench/model_audit/ws_widthtilt'))
    a = ap.parse_args()
    inj = dict(kv.split('=', 1) for kv in a.inject)
    cache = a.cache or os.path.expanduser(f'~/x17/cosmic_bench/vladder/{a.det}/cache.pkl')
    bundle = a.bundle or os.path.expanduser(f'~/x17/cosmic_bench/model_audit/{a.det}/calib_bundle')
    ev = pickle.load(open(cache, 'rb')); ids = sorted(ev)[a.start:]
    if a.tan_min > 0:
        ids = [i for i in ids if max(abs(ev[i].get('tan_x', 0)), abs(ev[i].get('tan_y', 0))) >= a.tan_min]
    # stratify: all steep events plus a sample of the rest, up to n
    ids = ids[:a.n]
    os.makedirs(a.out, exist_ok=True)
    with ProcessPoolExecutor(a.jobs, initializer=_init, initargs=(cache, bundle, 24, inj)) as ex:
        rows = [r for rr in ex.map(one, ids, chunksize=4) for r in rr]
    R = np.array(rows, float)
    o = os.path.join(a.out, f'toy_{a.det}_{a.tag}.npz')
    np.savez(o, per=R, inject=json.dumps(inj))
    for vi, p in enumerate('xy'):
        m = R[:, 1] == vi; t = np.abs(R[m, 2]); r = R[m, 4] / R[m, 3]
        s = []
        for lo, hi in ((0.08, 0.14), (0.14, 0.20), (0.20, 0.28), (0.28, 0.45)):
            b = (t >= lo) & (t < hi)
            s.append(f'{lo:.2f}-{hi:.2f}: {np.median(r[b]):.3f} (n={b.sum()})' if b.sum() > 3 else f'{lo}-{hi}: -')
        print(a.det, p, a.tag, ' | '.join(s), flush=True)
    print('wrote', o)


if __name__ == '__main__':
    main()
