def stagger(items, x_of, size=20, pad=18, right=None):
    """items sorted by x -> list of (item, row, anchor); greedy label rows, as many as needed.  A label that would run
    past ``right`` is drawn to the left of its point (anchor 'end')."""
    ends = []
    out = []
    for it in items:
        x = x_of(it)
        w = 0.55 * size * len(it[1]) + 70
        lo, hi, anc = (x - 4, x + w, 'start') if (right is None or x + w < right) else (x - w, x + 4, 'end')
        r = next((k for k, e in enumerate(ends) if e < lo - pad), None)
        if r is None:
            ends.append(hi); r = len(ends) - 1
        else:
            ends[r] = hi
        out.append((it, r, anc))
    return out


def period_svg(i, W=1664):
    a, b, lab = td.PERIODS[i]
    t0, t1 = D(a) - dt.timedelta(days=1), D(b) + dt.timedelta(days=1)
    span = (t1 - t0).days
    L0, R0 = 210, W - 30

    def X(d):
        return L0 + (R0 - L0) * (D(d) - t0).days / span

    ms = sorted((m for m in td.MILESTONES if period_of(m[0]) == i), key=lambda m: m[0])
    placed = stagger(ms, lambda m: X(m[0]), right=W)
    nrow = max([r for _, r, _ in placed] + [0]) + 1
    RH = 30
    axis_y = 24 + RH * nrow
    les = sorted((L for L in td.LESSONS if period_of(L[0]) == i), key=lambda L: L[0])
    used = [k for k in ORDER if any(L[4] == k for L in les)]
    top = axis_y + 64
    lane = 38
    H = int(top + lane * len(used) + 10)
    g = [sd.line(L0, axis_y, R0, axis_y, sd.INK, 3)]
    # ticks: days for a short period, else months
    if span <= 14:
        d = t0 + dt.timedelta(days=1)
        while d < t1:
            x = X(d.isoformat()); g.append(sd.line(x, axis_y, x, axis_y + 10, sd.MUT, 1.5))
            g.append(sd.T(x, axis_y + 36, d.strftime('%a %d %b'), 20)); d += dt.timedelta(days=1)
    else:
        d = dt.date(t0.year, t0.month, 1)
        while d < t1:
            if d >= t0:
                x = X(d.isoformat()); g.append(sd.line(x, axis_y, x, axis_y + 10, sd.MUT, 1.5))
                g.append(sd.T(x, axis_y + 36, d.strftime('%b %Y'), 20))
            d = dt.date(d.year + (d.month == 12), d.month % 12 + 1, 1)
    for (m, r, anc) in placed:
        x = X(m[0]); y = axis_y - 20 - RH * r
        tip = m[0] + ' · ' + td.AREAS[m[2]]
        g.append(sd.line(x, y + 8, x, axis_y, sd.MUT, 1.2, '3 3'))
        g.append(f'<circle cx="{x:.1f}" cy="{axis_y}" r="8" fill="{sd.INK}"{sd.tipattr(tip)}/>')
        g.append(sd.T(x + (-6 if anc == 'end' else -4), y, f'{D(m[0]).strftime("%d %b")} · {sd.esc(m[1])}', 20,
                      sd.INK, anc, tip=tip))
    for j, k in enumerate(used):
        y = top + lane * (j + 0.5)
        g.append(sd.line(L0, y, R0, y, sd.RULE, 1))
        g.append(sd.T(L0 - 16, y + 7, ST[k][0], 21, ST[k][1], 'end', 600, tip=ST[k][2]))
    seen = collections.Counter()
    for L in les:
        j = used.index(L[4]); y = top + lane * (j + 0.5)
        n = seen[(L[0], L[4])]; seen[(L[0], L[4])] += 1
        x = X(L[0]) + 18 * n
        g.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="11" fill="{ST[L[4]][1]}" stroke="#fff" stroke-width="2"'
                 f'{sd.tipattr(lesson_tip(L))}/>')
    return sd.svg(W, H, ''.join(g), f'{lab} timeline'), les


