def D(s):
    return dt.date.fromisoformat(s)


def period_of(date):
    for i, (a, b, _) in enumerate(td.PERIODS):
        if D(a) <= D(date) <= D(b):
            return i
    return len(td.PERIODS) - 1


def commits_per_month():
    try:
        out = subprocess.run(['git', '-C', REPO, 'log', '--format=%ad', '--date=format:%Y-%m'], capture_output=True,
                             text=True, check=True).stdout.split()
    except Exception:
        return {}
    return collections.Counter(out)


def chip(status, size=20):
    lab, c, _ = ST[status]
    return (f'<span style="display:inline-block;padding:2px 10px;border-radius:10px;background:{c};color:#fff;'
            f'font-size:{size}px;font-weight:600;white-space:nowrap">{lab}</span>')


def lesson_tip(L):
    d, a, les, where, s = L
    return f'{d} · {td.AREAS[a]}\n{les}\n\nChain: {where}\nStatus: {ST[s][0]}'


